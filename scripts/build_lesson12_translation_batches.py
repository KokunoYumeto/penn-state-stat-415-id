def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def boundary(value: str) -> tuple[str, str]:
    lead = value[: len(value) - len(value.lstrip())]
    trail = value[len(value.rstrip()):]
    return lead, trail


def atomic_write(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix=path.name + ".", suffix=".tmp", delete=False) as stream:
        stream.write(payload)
        temporary = Path(stream.name)
    temporary.replace(path)


def compute() -> dict[Path, bytes]:
    raw = TEMPLATE.read_bytes()
    if raw.startswith(b"\xef\xbb\xbf") or b"\r" in raw or not raw.endswith(b"\n"):
        raise RuntimeError("Lesson 12 segment template is not canonical UTF-8/LF")
    rows = list(csv.DictReader(io.StringIO(raw.decode("utf-8"), newline="")))
    expected_ids = [f"{DOCUMENT_ID}-S{i:04d}" for i in range(1, 581)]
    if tuple(rows[0]) != FIELDS or len(rows) != 580 or [r["segment_id"] for r in rows] != expected_ids:
        raise RuntimeError("Lesson 12 segment template boundary differs")
    if set(TARGETS) != set(range(1, 581)):
        missing = sorted(set(range(1, 581)) - set(TARGETS))
        extra = sorted(set(TARGETS) - set(range(1, 581)))
        raise RuntimeError(f"Lesson 12 target map differs; missing={missing}, extra={extra}")
    translated: list[dict[str, str]] = []
    for ordinal, row in enumerate(rows, start=1):
        if row["document_id"] != DOCUMENT_ID or row["component_id"] != COMPONENT_ID or row["status"] != "pending" or row["target_text"]:
            raise RuntimeError(f"Lesson 12 source row differs: {row['segment_id']}")
        if sha256(row["source_text"].encode("utf-8")) != row["source_sha256"]:
            raise RuntimeError(f"Lesson 12 source hash differs: {row['segment_id']}")
        lead, trail = boundary(row["source_text"])
        core = TARGETS[ordinal]
        if not core.strip() or core != core.strip() or "�" in core:
            raise RuntimeError(f"Lesson 12 target core is invalid: {row['segment_id']}")
        target = lead + core + trail
        if boundary(target) != (lead, trail):
            raise RuntimeError(f"Lesson 12 target boundary whitespace differs: {row['segment_id']}")
        translated.append({**row, "target_text": target, "status": "translated"})
    outputs: dict[Path, bytes] = {}
    for name, (low, high) in RANGES.items():
        stream = io.StringIO(newline="")
        writer = csv.DictWriter(stream, fieldnames=FIELDS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(translated[low - 1:high])
        outputs[OUTPUTS[name]] = stream.getvalue().encode("utf-8")
    return outputs


def main() -> None:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check-only", action="store_true")
    args = parser.parse_args()
    outputs = compute()
    if args.write:
        for path, payload in outputs.items():
            atomic_write(path, payload)
        state = "written"
    else:
        for path, payload in outputs.items():
            if not path.is_file() or path.read_bytes() != payload:
                raise RuntimeError(f"Lesson 12 batch differs: {path.relative_to(ROOT)}")
        state = "verified"
    print(json.dumps({"mode": state, "batches": {p.name: {"bytes": len(b), "sha256": sha256(b)} for p, b in outputs.items()}}, ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    main()
